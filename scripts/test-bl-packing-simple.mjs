import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const require=createRequire(new URL('../frontend/package.json',import.meta.url));
const React=require('react'),{create,act}=require('react-test-renderer'),{MemoryRouter}=require('react-router-dom'),{createServer}=require('vite');
const ReactDOM=require('react-dom'),portal=ReactDOM.createPortal;
ReactDOM.createPortal=children=>children;
globalThis.document={body:{style:{}},documentElement:{},getElementById:()=>null,addEventListener:()=>{},removeEventListener:()=>{},createElement:()=>({click(){}})};
globalThis.localStorage={getItem:()=>null,setItem:()=>{}};
globalThis.window={localStorage,location:{href:'http://localhost'},addEventListener:()=>{},removeEventListener:()=>{}};
const server=await createServer({root:fileURLToPath(new URL('../frontend',import.meta.url)),server:{middlewareMode:true,hmr:false},appType:'custom'});
let mounted;
try {
 const {LanguageProvider}=await server.ssrLoadModule('/src/i18n/LanguageContext.jsx');
 const {default:Documents}=await server.ssrLoadModule('/src/pages/BL/RegisterDocuments.jsx');
 const {default:Workspace}=await server.ssrLoadModule('/src/pages/BL/BLPackingWorkspace.jsx');
 const {default:api}=await server.ssrLoadModule('/src/api/client.js');
 const own={id:'own',filename:'own.xlsx',originalName:'PARTNER-A.xlsx',category:'PACKING_LIST',scope:{type:'BL',billIds:['a']}};
 const output={id:'old',filename:'old.xlsx',category:'INTERNAL_PACKING_LIST',originalName:'HEAD-OLD.xlsx',createdAt:'2026-01-01',scope:{type:'BL',billIds:['a']}};
 const latest={...output,id:'new',originalName:'HEAD-NEW.xlsx',createdAt:'2026-02-01'};
 const voyage={id:'voyage',category:'INTERNAL_PACKING_RECAP',originalName:'VOYAGE.xlsx',scope:{type:'VOYAGE'}};
 let bill={id:'a',billNumber:'BL-A',journeyId:'j',version:1,containers:[{number:'CONT-A'}],files:[own,output,latest,voyage],registerData:{operational:{packing:{status:'CONFIRMED',sourceFileIds:['own'],groups:[{id:'g',sourceFileId:'own',containerNumber:'CONT-A',recipientName:'OWN RECIPIENT',items:[{id:'i',description:'Rice',packages:2,packageUnit:'KARUNG'}]}]}}}};
 const calls=[];
 api.get=async url=>{calls.push(url);return {data:url.endsWith('/files')?{files:bill.files}:bill};};
 const mount=async(Component,props,language='id')=>{if(mounted)await act(async()=>mounted.unmount());await act(async()=>{mounted=create(React.createElement(LanguageProvider,{initialLanguage:language},React.createElement(MemoryRouter,null,React.createElement(Component,props))));});};
 const text=node=>typeof node==='string'?node:(Array.isArray(node)?node:node?.children||[]).map(text).join('');
 const button=label=>mounted.root.findAllByType('button').find(node=>text(node).trim()===label);
 const click=async label=>{const node=button(label);assert(node,'Missing button: '+label);assert(!node.props.disabled,'Disabled button: '+label);await act(async()=>node.props.onClick());};
 await mount(Documents,{bill,owner:'PACKING',packingView:'SOURCES',compact:true});
 assert.equal(mounted.root.findAllByProps({type:'file'}).length,0,'Compact source form stays closed until requested');
 await click('Unggah PL mitra');
 assert.equal(mounted.root.findAllByProps({type:'file'}).length,1);
 console.log('PASS compact document upload opens only on demand');
 await mount(Documents,{bill,owner:'PACKING',packingView:'RESULTS',compact:true});
 assert(text(mounted.toJSON()).includes('HEAD-NEW.xlsx'));
 assert(!text(mounted.toJSON()).includes('HEAD-OLD.xlsx'),'Only latest result is initially shown');
 assert(!text(mounted.toJSON()).includes('VOYAGE.xlsx'),'Voyage is not a B/L result');
 await click('Riwayat revisi');
 assert(text(mounted.toJSON()).includes('HEAD-OLD.xlsx'));
 const preview=mounted.root.findAllByType('button').find(node=>node.props['aria-label']==='Lihat HEAD-OLD.xlsx');
 assert(preview,'Each saved revision has direct view action');
 await act(async()=>preview.props.onClick());
 assert(mounted.root.findAll(node=>node.props.endpoint==='/bl-register/a/files/old').length>0);
 console.log('PASS latest output, expandable revisions and exact revision preview');
 const shared={...output,id:'shared',category:'PACKING_HEADER',originalName:'SHARED-HEAD.xlsx',createdAt:'2026-03-01',scope:{type:'SHARED',billIds:['a','b'],billNumbers:['BL-A','BL-B']}};
 bill={...bill,files:[...bill.files,shared]};
 await mount(Documents,{bill,owner:'PACKING',packingView:'RESULTS',compact:true});
 assert(text(mounted.toJSON()).includes('HEAD-NEW.xlsx'),'Newer shared output must not replace latest B/L-only result');
 assert(text(mounted.toJSON()).includes('Referensi hasil bersama'));
 assert(text(mounted.toJSON()).includes('BL-B'),'Shared ownership remains explicit');
 const sharedCard=mounted.root.findByProps({'data-shared-output':'shared'});
 assert(text(sharedCard).includes('Kepala Packing List'));
 assert(!text(sharedCard).includes('Hasil terbaru'));
 assert(sharedCard.findAllByType('button').some(node=>node.props['aria-label']==='Lihat SHARED-HEAD.xlsx'));
 console.log('PASS shared output retains category and ownership outside latest B/L result');
 await mount(Workspace,{bill});
 const root=mounted.root.findByProps({'data-bl-packing-workspace':true});
 assert.equal(root.findAll(node=>node.type==='section'&&node.props['data-packing-primary']).length,2,'Only source and head/result are primary groups');
 assert.equal(mounted.root.findAll(node=>node.props['data-bl-packing-section']==='reviewed').length,0,'No always-open container review table');
 assert(button('Periksa rincian'));
 await click('Periksa rincian');
 assert(mounted.root.findAllByProps({'data-packing-workflow':true}).length>0,'Review opens existing scoped workflow');
 assert.equal(mounted.root.findAllByType('select').find(node=>node.props['aria-label']==='Sumber Packing List').props.value,'PARTNER_PL');
 console.log('PASS two packing groups and on-demand selected-B/L review');
 await mount(Workspace,{bill:{...bill,files:[],registerData:{}}});
 assert(text(mounted.toJSON()).includes('PL mitra belum tersedia. Anda tetap dapat membuat PL dari data manual atau Berita Acara.'));
 assert(button('Kelola PL B/L ini'),'Alternate workflow retained');
 await mount(Documents,{bill:{...bill,archived:true},owner:'BL',compact:true});
 assert(button('Unggah B/L').props.disabled,'Archived records cannot open upload');
 console.log('PASS neutral no-partner case and archived restrictions');
 await mount(Documents,{bill,owner:'SUPPORTING',compact:true},'en');
 assert(text(mounted.toJSON()).includes('Supporting shipment documents'));
 await mount(Workspace,{bill:{...bill,registerData:{}}},'en');
 assert(text(mounted.toJSON()).includes('Not reviewed'));
 console.log('PASS English secondary documents and review status');
 const categories=['INVOICE','TAX_INVOICE','PPH23_CERTIFICATE','PAYMENT_PROOF','FINAL','PACKING_LIST','POD','DELIVERY_ORDER','MANIFEST','SUPPORTING'];
 const financeBill={...bill,files:categories.map((category,i)=>({id:'doc'+i,filename:'file'+i,originalName:category+'-UNIQUE.pdf',category}))};
 bill=financeBill;
 await mount(Documents,{bill:financeBill,owner:'SUPPORTING',documentArea:'FINANCE',compact:true});
 for(const category of categories)assert.equal(text(mounted.toJSON()).includes(category+'-UNIQUE.pdf'),['INVOICE','TAX_INVOICE','PPH23_CERTIFICATE','PAYMENT_PROOF'].includes(category),'Finance owns only transaction and tax files: '+category);
 await click('Unggah bukti transaksi');
 assert.deepEqual(mounted.root.findAllByType('select').find(n=>n.props['aria-label']==='Kategori dokumen').findAllByType('option').map(n=>n.props.value),['PAYMENT_PROOF','INVOICE','TAX_INVOICE','PPH23_CERTIFICATE']);
 console.log('PASS finance file list and upload options exclude B/L, PL, receipts and shipping documents');
 bill={...bill,archived:true,files:[{id:'report',filename:'report.pdf',originalName:'ARCHIVED-REPORT.pdf',category:'RECEIVING_REPORT'}]};
 await mount(Workspace,{bill});
 assert(text(mounted.toJSON()).includes('ARCHIVED-REPORT.pdf'),'Archived receiving report is readable without creator permission');
 assert(mounted.root.findAllByType('button').some(n=>n.props['aria-label']==='Lihat ARCHIVED-REPORT.pdf'));
 console.log('PASS archived receiving report remains readable in Packing independently of creation');
} finally {
 if(mounted)await act(async()=>mounted.unmount());await server.close();ReactDOM.createPortal=portal;
 delete globalThis.document;delete globalThis.window;delete globalThis.localStorage;
}
