const router = require('express').Router();
const prisma = require('../prisma');
const { authenticate, authorize } = require('../middleware/auth');
const { STAFF, route, transaction } = require('../services/jpt');
const catalogs = require('../services/transportCatalogs');
router.use(authenticate, authorize(...STAFF, 'MANAGER', 'OPERATOR', 'VIEWER'));
router.get('/', route(async (req, res) => res.json(await catalogs.list(prisma, 'routes', req.query))));
router.post('/', authorize('ADMIN', 'SUPER_ADMIN'), route(async (req, res) => res.status(201).json(await transaction(tx => catalogs.save(tx, req.user, 'routes', null, req.body)))));
router.put('/:id', authorize('ADMIN', 'SUPER_ADMIN'), route(async (req, res) => res.json(await transaction(tx => catalogs.save(tx, req.user, 'routes', req.params.id, req.body)))));
module.exports = router;
